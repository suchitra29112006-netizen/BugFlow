    # Phase 2: Smart Triage Queue Impact Score (0-100)
    def calculate_smart_triage_score(self, issue: Issue, db: Session) -> Dict[str, Any]:
        score = 0
        reasons = []

        # 1. Severity
        sev = issue.severity
        if sev == IssueSeverity.CRITICAL:
            score += 30
            reasons.append("Critical severity rating (+30)")
        elif sev == IssueSeverity.HIGH:
            score += 20
            reasons.append("High severity rating (+20)")
        elif sev == IssueSeverity.MEDIUM:
            score += 10
            reasons.append("Medium severity rating (+10)")

        # 2. Priority
        prio = issue.priority
        if prio == IssuePriority.CRITICAL:
            score += 20
            reasons.append("Critical business priority (+20)")
        elif prio == IssuePriority.HIGH:
            score += 15
            reasons.append("High business priority (+15)")

        # 3. SLA & Age
        if getattr(issue, 'is_overdue', False):
            score += 15
            reasons.append("Overdue SLA target date (+15)")

        age_days = (datetime.utcnow() - issue.created_at).days if issue.created_at else 0
        if age_days > 3:
            age_pts = min(15, age_days * 3)
            score += age_pts
            reasons.append(f"Unresolved for {age_days} days (+{age_pts})")

        # 4. Reopen Count
        reopens = getattr(issue, 'reopen_count', 0) or 0
        if reopens > 0:
            reopen_pts = min(20, reopens * 10)
            score += reopen_pts
            reasons.append(f"Reopened {reopens} time(s) by QA (+{reopen_pts})")

        # 5. Similar defects
        similar = self.find_similar_defects(issue.id, issue.title, issue.description or "", db, limit=5)
        if similar:
            sim_pts = min(15, len(similar) * 5)
            score += sim_pts
            reasons.append(f"{len(similar)} related similar defect(s) in codebase (+{sim_pts})")

        # 6. Unassigned status
        if not issue.assigned_to or issue.assigned_to == 0:
            score += 10
            reasons.append("Currently unassigned (+10)")

        final_score = min(100, score)
        level = "Critical" if final_score >= 80 else ("High" if final_score >= 60 else "Moderate")

        return {
            "issue_id": issue.id,
            "impact_score": final_score,
            "risk_level": level,
            "rank_reasons": reasons if reasons else ["Baseline standard defect priority"],
            "why_explanation": f"Ranked #{issue.id} with Impact Score {final_score}/100 based on factors: " + ", ".join(reasons)
        }

