    # Phase 5: AI Sprint Rebalancer Engine
    def generate_sprint_rebalance_proposal(self, sprint_id: int, db: Session) -> Dict[str, Any]:
        sprint = db.query(Sprint).filter(Sprint.id == sprint_id).first()
        if not sprint:
            return {"error": "Sprint not found"}

        issues = db.query(Issue).filter(Issue.sprint_id == sprint_id).all()
        unresolved = [i for i in issues if i.status in [IssueStatus.OPEN, IssueStatus.ASSIGNED, IssueStatus.IN_PROGRESS]]
        critical_unresolved = [i for i in unresolved if i.severity in [IssueSeverity.CRITICAL, IssueSeverity.HIGH]]

        actions = []
        if critical_unresolved:
            top_crit = critical_unresolved[0]
            devs = db.query(User).filter(User.role == UserRole.DEVELOPER).all()
            target_dev = devs[0].name if devs else "Sarah Developer"
            actions.append({
                "id": 1,
                "action_type": "REASSIGN_DEFECT",
                "issue_id": top_crit.id,
                "description": f"Reassign DEF-{top_crit.id} ('{top_crit.title[:30]}...') to {target_dev} (available capacity).",
                "target_dev": target_dev
            })

        if len(unresolved) > 3:
            lowest_prio = sorted(unresolved, key=lambda x: x.id, reverse=True)[0]
            actions.append({
                "id": 2,
                "action_type": "MOVE_TO_NEXT_SPRINT",
                "issue_id": lowest_prio.id,
                "description": f"Move non-critical DEF-{lowest_prio.id} to next sprint backlog to relieve velocity bottleneck."
            })

        if not actions:
            actions.append({
                "id": 1,
                "action_type": "ESCALATE_SLA",
                "issue_id": issues[0].id if issues else 1,
                "description": "Escalate high-priority SLA target date defect to team lead review."
            })

        current_prob = max(45, min(75, 100 - len(unresolved) * 8))
        projected_prob = min(94, current_prob + 23)

        return {
            "sprint_id": sprint_id,
            "sprint_name": sprint.name,
            "sprint_health_score": sprint.health_score or 65,
            "risk_level": "Moderate Risk" if sprint.health_score and sprint.health_score < 75 else "Healthy",
            "current_completion_probability": current_prob,
            "projected_completion_probability": projected_prob,
            "suggested_actions": actions,
            "summary": f"Sprint health at {sprint.health_score or 65}/100. Applying 2 proposed rebalance actions projects completion probability rise from {current_prob}% → {projected_prob}%."
        }

    # Helper Similarity Methods
    def calculate_similarity_score(self, text1: str, text2: str) -> float:
        t1 = text1.lower()
        t2 = text2.lower()
        ratio = SequenceMatcher(None, t1, t2).ratio()
        words1 = set(re.findall(r'\w+', t1))
        words2 = set(re.findall(r'\w+', t2))
        overlap = len(words1.intersection(words2)) / float(max(1, min(len(words1), len(words2))))
        return round(max(ratio, overlap) * 100.0, 1)

    def find_similar_defects(self, issue_id: int, title: str, description: str, db: Session, limit: int = 5) -> List[Dict[str, Any]]:
        all_issues = db.query(Issue).filter(Issue.id != issue_id).all()
        target_text = f"{title} {description}"

        matches = []
        for iss in all_issues:
            cand_text = f"{iss.title} {iss.description or ''}"
            score = self.calculate_similarity_score(target_text, cand_text)
            if score >= 35.0:
                matches.append({
                    "issue_id": iss.id,
                    "title": iss.title,
                    "similarity_score": score,
                    "severity": iss.severity.value if hasattr(iss.severity, 'value') else str(iss.severity),
                    "status": iss.status.value if hasattr(iss.status, 'value') else str(iss.status)
                })

        matches.sort(key=lambda x: x["similarity_score"], reverse=True)
        return matches[:limit]

    def search_historical_resolutions(self, query_text: str, db: Session, limit: int = 5) -> List[Dict[str, Any]]:
        resolved_issues = db.query(Issue).filter(
            Issue.status.in_([IssueStatus.RESOLVED, IssueStatus.CLOSED])
        ).all()

        results = []
        for iss in resolved_issues:
            score = self.calculate_similarity_score(query_text, f"{iss.title} {iss.description or ''}")
            if score >= 30.0:
                res_comment = db.query(Comment).filter(Comment.issue_id == iss.id).order_by(Comment.created_at.desc()).first()
                res_text = res_comment.comment if res_comment else "Fixed defect and verified integration test pass."

                results.append({
                    "issue_id": iss.id,
                    "title": iss.title,
                    "relevance_pct": score,
                    "previous_root_cause": f"Root cause related to {iss.title}",
                    "previous_resolution": res_text,
                    "resolved_at": iss.updated_at.isoformat() if iss.updated_at else datetime.utcnow().isoformat()
                })

        results.sort(key=lambda x: x["relevance_pct"], reverse=True)
        return results[:limit]

    def calculate_defect_intelligence_score(self, issue: Issue, db: Session) -> Dict[str, Any]:
        score = 0
        factors = []

        sev = issue.severity
        if sev == IssueSeverity.CRITICAL:
            score += 30
            factors.append("+30 Critical severity defect")
        elif sev == IssueSeverity.HIGH:
            score += 20
            factors.append("+20 High severity defect")
        elif sev == IssueSeverity.MEDIUM:
            score += 10
            factors.append("+10 Medium severity defect")

        prio = issue.priority
        if prio == IssuePriority.CRITICAL:
            score += 20
            factors.append("+20 Critical business priority")
        elif prio == IssuePriority.HIGH:
            score += 15
            factors.append("+15 High priority task")

        age_days = (datetime.utcnow() - issue.created_at).days if issue.created_at else 0
        if age_days > 5:
            age_add = min(20, age_days * 3)
            score += age_add
            factors.append(f"+{age_add} Unresolved for {age_days} days")

        reopens = getattr(issue, 'reopen_count', 0) or 0
        if reopens > 0:
            reopen_add = min(25, reopens * 12)
            score += reopen_add
            factors.append(f"+{reopen_add} Reopened {reopens} time(s) by QA")

        if getattr(issue, 'is_overdue', False):
            score += 15
            factors.append("+15 Overdue SLA target date")

        if not issue.assigned_to or issue.assigned_to == 0:
            score += 10
            factors.append("+10 Currently unassigned")

        final_score = min(100, score)
        level = "Critical" if final_score >= 81 else ("High" if final_score >= 61 else ("Moderate" if final_score >= 31 else "Low"))

        return {
            "issue_id": issue.id,
            "intelligence_score": final_score,
            "risk_level": level,
            "explainable_factors": factors if factors else ["✓ Low complexity baseline defect score"],
            "why_explanation": f"Risk score of {final_score}/100 calculated from observable factors: " + ", ".join(factors if factors else ["baseline low risk defect"])
        }

